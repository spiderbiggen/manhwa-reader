package com.spiderbiggen.manga.data.usecase.update

import com.spiderbiggen.manga.domain.model.update.ChangeGroup
import com.spiderbiggen.manga.domain.model.update.ChangeKind
import kotlinx.collections.immutable.ImmutableList
import kotlinx.collections.immutable.toImmutableList

// Matches "- [`sha`](url) - **scope**: message *(PR #1 by @user)*" and captures the message.
// Older releases end in "*(commit by @user)*" instead of the pull request reference.
private val ENTRY_REGEX =
    Regex(
        """^[-*] \[[^\]]*]\([^)]*\) - (?:\*\*[^*]+\*\*: )?(.*?)(?: \*\((?:PR #\d+|commit) by @[^)]*\)\*)?$"""
    )

/**
 * Turns the release notes generated by the changelog action into the changes a user cares about.
 *
 * Only features, bug fixes and performance improvements are kept; sections such as refactors and
 * chores, as well as commit hashes, scopes and authors, are dropped.
 *
 * This is coupled to the format produced by the `requarks/changelog-action` step in
 * `.github/workflows/ci_release.yaml`. If that step or its configuration changes, update this
 * parser and its tests together, otherwise releases silently show up as maintenance releases.
 */
class ReleaseNotesParser {

    fun parse(body: String): ImmutableList<ChangeGroup> {
        val messages = mutableMapOf<ChangeKind, MutableList<String>>()
        var kind: ChangeKind? = null
        for (line in body.lineSequence()) {
            val trimmed = line.trim()
            if (trimmed.startsWith("#")) {
                kind = headingKind(trimmed)
            } else {
                val currentKind = kind
                val message = entryMessage(trimmed)
                if (currentKind != null && message != null) {
                    messages.getOrPut(currentKind, ::mutableListOf) += message
                }
            }
        }
        return ChangeKind.entries
            .mapNotNull { entry ->
                messages[entry]?.let { ChangeGroup(entry, it.toImmutableList()) }
            }
            .toImmutableList()
    }

    private fun entryMessage(line: String): String? =
        ENTRY_REGEX.matchEntire(line)
            ?.groupValues
            ?.get(1)
            ?.trim()
            ?.takeIf { it.isNotEmpty() }
            ?.replaceFirstChar { it.uppercaseChar() }

    private fun headingKind(heading: String): ChangeKind? {
        val text = heading.lowercase()
        return when {
            ":sparkles:" in text || "feature" in text -> ChangeKind.Feature
            ":bug:" in text || "bug" in text || "fix" in text -> ChangeKind.Fix
            ":zap:" in text || "performance" in text -> ChangeKind.Performance
            else -> null
        }
    }
}
